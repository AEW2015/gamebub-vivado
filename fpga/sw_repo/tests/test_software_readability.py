"""Keep source orientation and licensing visible without requiring AMD tools."""
from pathlib import Path
import importlib.util
import unittest

SW = Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location('software_formatter', SW / 'tools/format_sources.py')
FORMAT = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(FORMAT)


class SoftwareReadability(unittest.TestCase):
    def test_canonical_c_has_file_header_and_license_pointer(self):
        files = FORMAT.canonical_sources()
        self.assertGreaterEqual(len(files), 43)
        for path in files:
            with self.subTest(path=path.name):
                text = path.read_text()
                self.assertIn('SPDX-License-Identifier:', text[:300])
                self.assertIn('@file ' + path.name, text)
                self.assertIn('LICENSE.md at repository root', text[:1500])

    def test_generated_entrypoints_explain_source_and_safety(self):
        for path in (SW / 'lib/sw_apps').glob('*/src/main.c'):
            with self.subTest(app=path.parent.parent.name):
                text = path.read_text()
                self.assertIn('@brief', text)
                self.assertIn('Generated by tools/generate_app_templates.py', text)
                self.assertIn('Review gamebub_settings.h', text)

    def test_amd_license_is_retained(self):
        text = (SW / 'templates/CMakeLists.txt.in').read_text()
        self.assertIn('Advanced Micro Devices, Inc.', text)
        self.assertIn('SPDX-License-Identifier: MIT', text)


if __name__ == '__main__':
    unittest.main()
